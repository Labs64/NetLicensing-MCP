"""Generate the tool and prompt reference from the live MCP registry.

Writes ``docs/TOOLS.md`` (every tool with its parameters, every prompt with
its arguments) and refreshes the generated parts of ``README.md``:

- the tool tables between ``<!-- tools:start -->`` and ``<!-- tools:end -->``,
- the prompt tables between ``<!-- prompts:start -->`` and ``<!-- prompts:end -->``,
- inline counts marked ``<!-- count:tools -->61<!-- /count:tools -->`` (same
  for ``toolsets`` and ``prompts``), and ``"tool_count": N`` in JSON examples.

The registry is built with every tool enabled, so ``MCP_TOOLSETS`` and
``MCP_READ_ONLY`` do not change the output. The output is deterministic: tools
follow the ``TOOLSETS`` table, prompts their registration order; no timestamps.

Usage::

    python scripts/gen_tools_doc.py           # rewrite docs/TOOLS.md and README.md
    python scripts/gen_tools_doc.py --check   # exit 1 if either file is out of date

Only the standard library and this project are imported.
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import json
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# Importing the server registers every tool module in the server's order;
# import it before anything from netlicensing_mcp.mcp_tools.
import netlicensing_mcp.server as server
from netlicensing_mcp.app import new_server, register_tools
from netlicensing_mcp.prompts.audit import register_audit_prompts
from netlicensing_mcp.prompts.setup import register_setup_prompts
from netlicensing_mcp.toolsets import TOOLSET_NAMES, TOOLSETS, ToolFilter

ROOT = Path(__file__).resolve().parent.parent
TOOLS_MD = Path("docs/TOOLS.md")
README_MD = Path("README.md")
SERVER_JSON = Path("server.json")
COMMAND = "python scripts/gen_tools_doc.py"

GENERATED_NOTE = (
    f"<!-- Generated by scripts/gen_tools_doc.py from the tool registry. "
    f"Do not edit by hand; run `{COMMAND}`. -->"
)

#: Prompt groups in README / TOOLS.md order, with the function that registers them.
PROMPT_GROUPS: tuple[tuple[str, Callable[[Any], None]], ...] = (
    ("Audits", register_audit_prompts),
    ("Setup and troubleshooting", register_setup_prompts),
)

BADGE_LEGEND = "**R** = read-only, **W** = writes data, **D** = destructive (deletes data)"


# ── Registry ────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class Param:
    name: str
    type: str
    required: bool
    default: str
    description: str


@dataclass(frozen=True)
class ToolDoc:
    name: str
    toolset: str
    title: str
    badge: str
    summary: str
    body: str
    annotations: tuple[tuple[str, bool], ...]
    params: tuple[Param, ...]


@dataclass(frozen=True)
class PromptArg:
    name: str
    required: bool
    description: str


@dataclass(frozen=True)
class PromptDoc:
    name: str
    group: str
    title: str
    summary: str
    args: tuple[PromptArg, ...]


@dataclass(frozen=True)
class Registry:
    tools: tuple[ToolDoc, ...]
    prompts: tuple[PromptDoc, ...]

    def toolset(self, name: str) -> list[ToolDoc]:
        return [t for t in self.tools if t.toolset == name]


_ARGS_HEADER = re.compile(r"^Args:\s*$")
_ARG_LINE = re.compile(r"^(\s+)(\w+)(?:\s*\([^)]*\))?:\s*(.*)$")


def _split_doc(doc: str | None) -> tuple[str, str, dict[str, str]]:
    """Split a docstring into (summary, body, {arg: description}).

    ``inspect.cleandoc`` first: Python 3.13+ strips docstring indentation at
    compile time and 3.12 does not, so the text must not depend on it. The
    summary is the first paragraph on one line; the body is everything before
    a Google-style ``Args:`` section; the section gives the arg descriptions.
    """
    text = inspect.cleandoc(doc or "")
    lines = text.splitlines()
    args: dict[str, str] = {}
    cut = len(lines)
    for i, line in enumerate(lines):
        if _ARGS_HEADER.match(line):
            cut = i
            indent: int | None = None
            current: str | None = None
            for arg_line in lines[i + 1 :]:
                if arg_line.strip() and not arg_line[:1].isspace():
                    break  # next unindented section
                match = _ARG_LINE.match(arg_line)
                if match and (indent is None or len(match.group(1)) == indent):
                    indent = len(match.group(1))
                    current = match.group(2)
                    args[current] = match.group(3).strip()
                elif current is not None and arg_line.strip():
                    args[current] = f"{args[current]} {arg_line.strip()}".strip()
            break
    body = "\n".join(lines[:cut]).strip()
    summary = " ".join(body.split("\n\n")[0].split()) if body else ""
    return summary, body, args


def _type_of(schema: dict[str, Any]) -> str:
    """A short type name for a JSON schema (``string``, ``boolean | null``, ...)."""
    if "anyOf" in schema:
        return " | ".join(_type_of(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        return f"array of {_group(_type_of(items))}" if isinstance(items, dict) else "array"
    if kind == "object":
        values = schema.get("additionalProperties")
        if isinstance(values, dict) and values:
            return f"object of {_group(_type_of(values))}"
        return "object"
    if isinstance(kind, list):
        return " | ".join(str(k) for k in kind)
    return str(kind) if kind else "any"


def _group(text: str) -> str:
    return f"({text})" if " | " in text else text


def _badge(annotations: dict[str, Any]) -> str:
    """R, W or D from the MCP hints (spec defaults: readOnly false, destructive true)."""
    if annotations.get("readOnlyHint") is True:
        return "R"
    if annotations.get("destructiveHint") is False:
        return "W"
    return "D"


async def _collect_tools() -> list[ToolDoc]:
    # A fresh server with every tool: the shared ``mcp`` honours MCP_TOOLSETS /
    # MCP_READ_ONLY, this one does not.
    full = new_server(ToolFilter())
    register_tools(full, ToolFilter())
    listed = {t.name: t for t in await full.list_tools()}
    expected = [name for names in TOOLSETS.values() for name in names]
    if sorted(listed) != sorted(expected):
        missing = sorted(set(expected) - set(listed))
        extra = sorted(set(listed) - set(expected))
        raise RuntimeError(f"registry and TOOLSETS differ: missing={missing} extra={extra}")

    docs: list[ToolDoc] = []
    for toolset, names in TOOLSETS.items():
        for name in names:
            tool = listed[name]
            hints = tool.annotations.model_dump(exclude_none=True) if tool.annotations else {}
            hints.pop("title", None)
            summary, body, arg_docs = _split_doc(tool.description)
            schema = tool.inputSchema
            required = set(schema.get("required", []))
            params = tuple(
                Param(
                    name=pname,
                    type=_type_of(pschema),
                    required=pname in required,
                    default="" if pname in required else json.dumps(pschema.get("default")),
                    description=arg_docs.get(pname, ""),
                )
                for pname, pschema in schema.get("properties", {}).items()
            )
            docs.append(
                ToolDoc(
                    name=name,
                    toolset=toolset,
                    title=tool.title or "",
                    badge=_badge(hints),
                    summary=summary,
                    body=body,
                    annotations=tuple(sorted((k, bool(v)) for k, v in hints.items())),
                    params=params,
                )
            )
    return docs


async def _collect_prompts() -> list[PromptDoc]:
    docs: list[PromptDoc] = []
    for group, register in PROMPT_GROUPS:
        holder = new_server(ToolFilter())
        register(holder)
        for prompt in await holder.list_prompts():
            summary, _body, arg_docs = _split_doc(prompt.description)
            args = tuple(
                PromptArg(
                    name=a.name,
                    required=bool(a.required),
                    description=a.description or arg_docs.get(a.name, ""),
                )
                for a in prompt.arguments or []
            )
            docs.append(PromptDoc(prompt.name, group, prompt.title or "", summary, args))
    served = [p.name for p in await server.mcp.list_prompts()]
    if sorted(served) != sorted(p.name for p in docs):
        raise RuntimeError(
            "the server registers prompts that PROMPT_GROUPS in scripts/gen_tools_doc.py "
            f"does not cover: served={served}, grouped={[p.name for p in docs]}"
        )
    return docs


def collect() -> Registry:
    """Build the full registry (all tools and prompts), independent of ``MCP_*`` env."""

    async def _both() -> Registry:
        return Registry(tuple(await _collect_tools()), tuple(await _collect_prompts()))

    return asyncio.run(_both())


# ── Rendering ───────────────────────────────────────────────────────────────


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _code(text: str) -> str:
    return f"`{text}`"


def _tool_anchor(name: str) -> str:
    return name  # GitHub's slug of the heading "### `name`"


def _toolset_anchor(name: str) -> str:
    return f"toolset-{name}"  # slug of "## Toolset `name`"


def _counts_line(reg: Registry) -> str:
    return (
        f"{len(reg.tools)} tools in {len(TOOLSET_NAMES)} toolsets, plus {len(reg.prompts)} prompts."
    )


def _tool_table(tools: list[ToolDoc], link: Callable[[str], str]) -> list[str]:
    rows = ["| Tool | Title | Access | Description |", "|---|---|---|---|"]
    for t in tools:
        rows.append(
            f"| [{_code(t.name)}]({link(t.name)}) | {_cell(t.title)} | {t.badge} "
            f"| {_cell(t.summary)} |"
        )
    return rows


def _prompt_args(prompt: PromptDoc) -> str:
    if not prompt.args:
        return "—"
    return ", ".join(
        _code(a.name) if a.required else f"{_code(a.name)} (optional)" for a in prompt.args
    )


def _prompt_table(prompts: list[PromptDoc], link: Callable[[str], str] | None) -> list[str]:
    rows = ["| Prompt | Purpose | Arguments |", "|---|---|---|"]
    for p in prompts:
        name = f"[{_code(p.name)}]({link(p.name)})" if link else _code(p.name)
        rows.append(f"| {name} | {_cell(p.summary)} | {_prompt_args(p)} |")
    return rows


def render_tools_md(reg: Registry) -> str:
    out: list[str] = [
        "# Tool reference",
        "",
        GENERATED_NOTE,
        "",
        f"The NetLicensing MCP server has {_counts_line(reg)} "
        "This page lists all of them, as the server registers them with every toolset "
        "enabled. `MCP_TOOLSETS` and `MCP_READ_ONLY` shrink the list a client sees; "
        "see [Reduce the tool list / read-only mode]"
        "(../README.md#reduce-the-tool-list--read-only-mode).",
        "",
        f"Badges: {BADGE_LEGEND}. They follow the tool annotations "
        "(`readOnlyHint`, `destructiveHint`) that the server sends to clients.",
        "",
        "Every parameter that is not required may be left out; the default is what the "
        'tool then uses. String parameters with the default `""` mean '
        '"not set" (on updates: "leave unchanged").',
        "",
        "## Contents",
        "",
    ]
    for name in TOOLSET_NAMES:
        count = len(reg.toolset(name))
        out.append(f"- [Toolset `{name}`](#{_toolset_anchor(name)}) ({count} tools)")
    out += ["- [Prompts](#prompts)", ""]

    for name in TOOLSET_NAMES:
        tools = reg.toolset(name)
        out += [f"## Toolset `{name}`", ""]
        out += _tool_table(tools, lambda n: f"#{_tool_anchor(n)}")
        out.append("")
        for t in tools:
            hints = ", ".join(f"`{k}={'true' if v else 'false'}`" for k, v in t.annotations)
            out += [f"### `{t.name}`", ""]
            out += [f"**{t.title}** · {t.badge} · {hints}" if hints else f"**{t.title}**", ""]
            out += [t.body, ""]
            if t.params:
                out += [
                    "| Parameter | Type | Required | Default | Description |",
                    "|---|---|---|---|---|",
                ]
                for param in t.params:
                    default = _code(param.default) if param.default else "—"
                    required = "yes" if param.required else "no"
                    out.append(
                        f"| {_code(param.name)} | {_cell(param.type)} | {required} "
                        f"| {_cell(default)} | {_cell(param.description)} |"
                    )
            else:
                out.append("No parameters.")
            out.append("")

    out += [
        "## Prompts",
        "",
        "Prompts are always registered, whatever `MCP_TOOLSETS` and `MCP_READ_ONLY` say.",
        "",
    ]
    for group, _register in PROMPT_GROUPS:
        prompts = [p for p in reg.prompts if p.group == group]
        out += [f"### {group}", ""]
        out += _prompt_table(prompts, lambda n: f"#{n}")
        out.append("")
        for p in prompts:
            out += [f"#### `{p.name}`", ""]
            if p.title:
                out += [f"**{p.title}**", ""]
            out += [p.summary, ""]
            if p.args:
                out += ["| Argument | Required | Description |", "|---|---|---|"]
                for a in p.args:
                    out.append(
                        f"| {_code(a.name)} | {'yes' if a.required else 'no'} "
                        f"| {_cell(a.description)} |"
                    )
            else:
                out.append("No arguments.")
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def render_readme_tools(reg: Registry) -> str:
    out = [
        GENERATED_NOTE,
        "",
        f"{_counts_line(reg)} {BADGE_LEGEND}. "
        "Parameters for every tool: [docs/TOOLS.md](docs/TOOLS.md).",
        "",
    ]
    for name in TOOLSET_NAMES:
        tools = reg.toolset(name)
        out += [f"**Toolset `{name}`** ({len(tools)} tools)", ""]
        out += _tool_table(tools, lambda n: f"docs/TOOLS.md#{_tool_anchor(n)}")
        out.append("")
    return "\n".join(out)


def render_readme_prompts(reg: Registry) -> str:
    out = [GENERATED_NOTE, ""]
    for group, _register in PROMPT_GROUPS:
        prompts = [p for p in reg.prompts if p.group == group]
        out += [f"**{group}:**", ""]
        out += _prompt_table(prompts, lambda n: f"docs/TOOLS.md#{n}")
        out.append("")
    out.append("Argument details (formats, defaults): [docs/TOOLS.md](docs/TOOLS.md#prompts).")
    out.append("")
    return "\n".join(out)


def _replace_block(text: str, marker: str, content: str) -> str:
    start, end = f"<!-- {marker}:start -->", f"<!-- {marker}:end -->"
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    found = len(pattern.findall(text))
    if found != 1:
        raise RuntimeError(f"README.md must contain exactly one {start} ... {end} block")
    return pattern.sub(lambda _m: f"{start}\n{content}\n{end}", text)


def _replace_count(text: str, key: str, value: int) -> str:
    pattern = re.compile(rf"(<!-- count:{key} -->)\d+(<!-- /count:{key} -->)")
    return pattern.sub(lambda m: f"{m.group(1)}{value}{m.group(2)}", text)


def render_readme(reg: Registry, current: str) -> str:
    text = _replace_block(current, "tools", render_readme_tools(reg))
    text = _replace_block(text, "prompts", render_readme_prompts(reg))
    text = _replace_count(text, "tools", len(reg.tools))
    text = _replace_count(text, "toolsets", len(TOOLSET_NAMES))
    text = _replace_count(text, "prompts", len(reg.prompts))
    return re.sub(r'("tool_count": )\d+', lambda m: f"{m.group(1)}{len(reg.tools)}", text)


# ── Facts in server.json ────────────────────────────────────────────────────


def server_json_problems_from(data: dict[str, Any]) -> list[str]:
    """``server.json`` has no tool list; its ``MCP_TOOLSETS`` text must name every toolset."""
    expected = ", ".join(TOOLSET_NAMES) + ", or all"
    problems = []
    for package in data.get("packages", []):
        for var in package.get("environmentVariables", []):
            if var.get("name") == "MCP_TOOLSETS" and expected not in var.get("description", ""):
                problems.append(
                    f"server.json ({package.get('registryType')}): the MCP_TOOLSETS description "
                    f"must list the toolsets as '{expected}'"
                )
    return problems


def server_json_problems(root: Path | None = None) -> list[str]:
    path = (root or ROOT) / SERVER_JSON
    return server_json_problems_from(json.loads(path.read_text(encoding="utf-8")))


# ── Entry point ─────────────────────────────────────────────────────────────


def _read(path: Path) -> str:
    with path.open(encoding="utf-8", newline="") as fh:
        return fh.read()


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def expected_files(root: Path | None = None, reg: Registry | None = None) -> dict[Path, str]:
    """The generated content of every managed file, keyed by path relative to *root*."""
    root = root or ROOT
    reg = reg or collect()
    return {
        TOOLS_MD: render_tools_md(reg),
        README_MD: render_readme(reg, _read(root / README_MD)),
    }


def stale_files(root: Path | None = None, reg: Registry | None = None) -> list[Path]:
    """Managed files whose committed content differs from the generated one."""
    root = root or ROOT
    stale = []
    for rel, text in expected_files(root, reg).items():
        path = root / rel
        if not path.exists() or _read(path) != text:
            stale.append(rel)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if docs/TOOLS.md or README.md is outdated"
    )
    args = parser.parse_args(argv)

    problems = server_json_problems()
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)

    if args.check:
        stale = stale_files()
        for rel in stale:
            print(
                f"error: {rel.as_posix()} is out of date with the tool registry.", file=sys.stderr
            )
        if stale:
            print(f"Run `{COMMAND}` and commit the result.", file=sys.stderr)
        return 1 if stale or problems else 0

    for rel, text in expected_files().items():
        path = ROOT / rel
        if not path.exists() or _read(path) != text:
            _write(path, text)
            print(f"updated {rel.as_posix()}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
